/**
 * Material 3 Dark Color Scheme tailored for Accu-Vis Clinical Operator Station
 */
private val AccuVisDarkColorScheme = darkColorScheme(
    primary = PrimaryYellow,
    onPrimary = TextOnYellow,
    primaryContainer = PrimaryYellowDim,
    onPrimaryContainer = PrimaryYellow,
    secondary = SurfaceElevated,
    onSecondary = TextPrimary,
    background = DarkBackground,
    onBackground = TextPrimary,
    surface = SurfaceDark,
    onSurface = TextPrimary,
    surfaceVariant = SurfaceElevated,
    onSurfaceVariant = TextSecondary,
    outline = SurfaceBorder,
    error = StatusError,
    onError = TextPrimary
)

val AccuVisShapes = Shapes(
    small = RoundedCornerShape(8.dp),
    medium = RoundedCornerShape(12.dp),
    large = RoundedCornerShape(16.dp),
    extraLarge = RoundedCornerShape(24.dp)
)

