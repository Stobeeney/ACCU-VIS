// Minimum standard touch target dimension for clinical touchscreens
val MinTouchTargetSize = 48.dp

@Composable
fun AccuVisTheme(
    darkTheme: Boolean = true, // Force dark theme for clinical operator contrast
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = AccuVisDarkColorScheme,
        typography = AccuVisTypography,
        shapes = AccuVisShapes,
        content = content
    )
}
